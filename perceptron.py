def feature_removal():

    print("\n" + "=" * 65)
    print("7. PERCEPTRON FEATURE REMOVAL CHALLENGE")
    print("=" * 65)

    # Full model
    (
        full_model,
        full_predictions,
        full_accuracy
    ) = train_perceptron(
        X_train,
        y_train,
        X_test,
        y_test
    )

    results = []

    # Remove one feature at a time
    for remove in range(4):

        keep = [
            i
            for i in range(4)
            if i != remove
        ]

        Xtr = X_train[
            :,
            keep
        ]

        Xte = X_test[
            :,
            keep
        ]

        (
            model,
            predictions,
            accuracy
        ) = train_perceptron(
            Xtr,
            y_train,
            Xte,
            y_test
        )

        accuracy_drop = (
            full_accuracy
            - accuracy
        ) * 100

        results.append({

            "Removed Feature":
                feature_names[remove],

            "Accuracy (%)":
                round(
                    accuracy * 100,
                    2
                ),

            "Accuracy Drop (%)":
                round(
                    accuracy_drop,
                    2
                ),

            "Epochs":
                model.epochs
        })

    result = pd.DataFrame(
        results
    )

    print(
        "\nAccuracy with all features:",
        round(
            full_accuracy * 100,
            2
        ),
        "%"
    )

    print(
        "\nFeature Removal Results:"
    )

    print(
        result.to_string(
            index=False
        )
    )

    # Find most important feature
    worst = result.loc[
        result[
            "Accuracy Drop (%)"
        ].idxmax()
    ]

    print(
        "\nMost influential feature:",
        worst[
            "Removed Feature"
        ]
    )


