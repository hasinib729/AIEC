# CUSTOM SINGLE-LAYER PERCEPTRON
# ============================================================

class Perceptron:

    def __init__(
        self,
        learning_rate=0.01,
        max_epochs=100
    ):

        self.learning_rate = learning_rate
        self.max_epochs = max_epochs

        self.weights = None
        self.bias = 0

        self.epochs = 0
        self.converged = False

    # --------------------------------------------------------
    # STEP ACTIVATION FUNCTION
    # --------------------------------------------------------

    def step(self, z):

        if z >= 0:
            return 1
        else:
            return 0

    # --------------------------------------------------------
    # TRAINING USING PERCEPTRON LEARNING RULE
    # --------------------------------------------------------

    def fit(self, X, y, order=None):

        n_samples, n_features = X.shape

        # Initialize weights and bias
        self.weights = np.zeros(n_features)
        self.bias = 0

        self.converged = False

        # Training order
        if order is None:
            order = np.arange(n_samples)

        # Epoch loop
        for epoch in range(
            1,
            self.max_epochs + 1
        ):

            errors = 0

            # Process samples
            for i in order:

                x = X[i]
                target = y[i]

                # Weighted sum
                z = (
                    np.dot(
                        x,
                        self.weights
                    )
                    + self.bias
                )

                # Step activation
                prediction = self.step(z)

                # Error
                error = target - prediction

                # Perceptron learning rule
                self.weights += (
                    self.learning_rate
                    * error
                    * x
                )

                self.bias += (
                    self.learning_rate
                    * error
                )

                if error != 0:
                    errors += 1

            self.epochs = epoch

            # Check convergence
            if errors == 0:

                self.converged = True
                break

        return self

    # --------------------------------------------------------
    # PREDICTION
    # --------------------------------------------------------

    def predict(self, X):

        predictions = []

        for x in X:

            z = (
                np.dot(
                    x,
                    self.weights
                )
                + self.bias
            )

            prediction = self.step(z)

            predictions.append(prediction)

        return np.array(predictions)

    # --------------------------------------------------------
    # WEIGHTED SUM
    # --------------------------------------------------------

    def weighted_sum(self, X):

        return (
            np.dot(
                X,
                self.weights
            )
            + self.bias
        )


# ============================================================
# HELPER FUNCTION
# ============================================================

def train_perceptron(
    Xtr,
    ytr,
    Xte,
    yte,
    order=None
):

    model = Perceptron(
        learning_rate=0.01,
        max_epochs=100
    )

    model.fit(
        Xtr,
        ytr,
        order
    )

    predictions = model.predict(Xte)

    accuracy = accuracy_score(
        yte,
        predictions
    )

    return (
        model,
        predictions,
        accuracy
    )


