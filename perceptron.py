def sample_order_challenge():

    print("\n" + "=" * 65)
    print("4. TRAINING SAMPLE ORDER CHALLENGE")
    print("=" * 65)

    n = len(X_train)

    rng = np.random.default_rng(42)

    # Different sample orders
    class_0 = np.where(
        y_train == 0
    )[0]

    class_1 = np.where(
        y_train == 1
    )[0]

    orders = {

        "Original":
            np.arange(n),

        "Reverse":
            np.arange(n)[::-1],

        "Random":
            rng.permutation(n),

        "Class-wise":
            np.concatenate([
                class_0,
                class_1
            ])
    }

    results = []

    for name, order in orders.items():

        (
            model,
            predictions,
            accuracy
        ) = train_perceptron(
            X_train,
            y_train,
            X_test,
            y_test,
            order
        )

        results.append({

            "Order":
                name,

            "Epochs":
                model.epochs,

            "Accuracy (%)":
                round(
                    accuracy * 100,
                    2
                ),

            "Bias":
                round(
                    model.bias,
                    4
                ),

            "Converged":
                model.converged
        })

    result = pd.DataFrame(
        results
    )

    print(
        result.to_string(
            index=False
        )
    )

    print(
        "\nObservation:"
    )

    print(
        "Changing the training sample order can "
        "change convergence speed and final weights."
    )


