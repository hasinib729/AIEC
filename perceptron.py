def borderline_detector():

    print("\n" + "=" * 65)
    print("5. BORDERLINE SAMPLE DETECTOR")
    print("=" * 65)

    (
        model,
        predictions,
        accuracy
    ) = train_perceptron(
        X_train,
        y_train,
        X_test,
        y_test
    )

    # Calculate weighted sums
    weighted_sum = model.weighted_sum(
        X_test
    )

    # Distance from decision boundary
    distance = np.abs(
        weighted_sum
    )

    # Five closest samples
    indices = np.argsort(
        distance
    )[:5]

    result = pd.DataFrame({

        "Sample":
            indices + 1,

        "Actual":
            y_test[
                indices
            ],

        "Predicted":
            predictions[
                indices
            ],

        "Weighted Sum":
            np.round(
                weighted_sum[
                    indices
                ],
                5
            ),

        "Distance":
            np.round(
                distance[
                    indices
                ],
                5
            )
    })

    print(
        "\nTop 5 Borderline Samples:"
    )

    print(
        result.to_string(
            index=False
        )
    )

    print(
        "\nSmaller distance = closer to "
        "the decision boundary."
    )


